"""AquaSense milestone 2: unsupervised leak *detection*, not yet localization.

Put this file next to a leak-free EPANET export called network.inp.
Install: python -m pip install wntr numpy pandas scikit-learn joblib
Run: python train_anomaly_detector.py

The model sees only virtual pressure/flow sensor data, never the leak location.
All results are generated by EPANET through WNTR.
"""
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import wntr
from sklearn.ensemble import IsolationForest

NETWORK_FILE = Path("network.inp")
OUTPUT_DIR = Path("ml_results")

# Matches the example network with junctions 2-6 and source pipe 1.
PRESSURE_SENSORS = ["4", "6"]  # metres of water head
FLOW_SENSORS = ["1"]           # L/s
LEAK_TEST_JUNCTION = "4"
LEAK_COEFFICIENT = 0.0005       # WNTR SI units: m^3/s/sqrt(m)

TRAIN_NORMAL = 160
TEST_NORMAL = 40
TEST_LEAK = 40
NOISE_PRESSURE_STD = 0.08  # metres
NOISE_FLOW_STD = 0.08      # L/s

rng = np.random.default_rng(42)
FEATURES = ([f"pressure_{j}_m" for j in PRESSURE_SENSORS]
            + [f"flow_{p}_lps" for p in FLOW_SENSORS])


def observation(leak_junction=None, coefficient=LEAK_COEFFICIENT):
    """Generate one observation under varied, unknown consumer demand.

    The leak identity influences EPANET's hidden simulation, not the feature vector.
    """
    wn = wntr.network.WaterNetworkModel(str(NETWORK_FILE))
    wn.options.time.duration = 0  # one steady hydraulic snapshot at t=0

    for junction_name in wn.junction_name_list:
        wn.get_node(junction_name).emitter_coefficient = 0.0

    # Simulate realistic variability in consumption, including local fluctuations.
    overall_multiplier = rng.uniform(0.90, 1.10)
    for junction_name in wn.junction_name_list:
        j = wn.get_node(junction_name)
        local_multiplier = rng.uniform(0.95, 1.05)
        for demand in j.demand_timeseries_list:
            demand.base_value *= overall_multiplier * local_multiplier

    if leak_junction is not None:
        wn.get_node(leak_junction).emitter_coefficient = coefficient

    # A common file prefix is reused sequentially (temporary EPANET result files).
    results = wntr.sim.EpanetSimulator(wn).run_sim(
        file_prefix=str(OUTPUT_DIR / "hydraulic_run")
    )

    values = []
    for junction_name in PRESSURE_SENSORS:
        p = float(results.node["pressure"].loc[0, junction_name])
        values.append(p + rng.normal(0, NOISE_PRESSURE_STD))
    for pipe_name in FLOW_SENSORS:
        q_lps = float(results.link["flowrate"].loc[0, pipe_name]) * 1000
        values.append(q_lps + rng.normal(0, NOISE_FLOW_STD))

    return values


def classify(model, obs):
    frame = pd.DataFrame([obs], columns=FEATURES)
    raw_prediction = int(model.predict(frame)[0])
    score = float(model.decision_function(frame)[0])
    return "ANOMALY" if raw_prediction == -1 else "NORMAL", score


def main():
    if not NETWORK_FILE.exists():
        raise FileNotFoundError(
            "Cannot find network.inp. Export the leak-free network from EPANET "
            "and put it in the same folder as this script."
        )
    OUTPUT_DIR.mkdir(exist_ok=True)

    check = wntr.network.WaterNetworkModel(str(NETWORK_FILE))
    for name in PRESSURE_SENSORS + [LEAK_TEST_JUNCTION]:
        if name not in check.junction_name_list:
            raise ValueError(f"Unknown junction {name!r}; edit PRESSURE_SENSORS or LEAK_TEST_JUNCTION")
    for name in FLOW_SENSORS:
        if name not in check.pipe_name_list:
            raise ValueError(f"Unknown pipe {name!r}; edit FLOW_SENSORS")

    print(f"Generating {TRAIN_NORMAL} leak-free training scenarios...")
    train = pd.DataFrame([observation() for _ in range(TRAIN_NORMAL)], columns=FEATURES)
    train.to_csv(OUTPUT_DIR / "normal_training_readings.csv", index=False)

    # Purely unsupervised: the training dataset contains NO simulated leaks or labels.
    model = IsolationForest(n_estimators=200, contamination=0.03, random_state=42)
    model.fit(train)
    joblib.dump({"model": model, "features": FEATURES}, OUTPUT_DIR / "detector.joblib")

    print(f"Testing on {TEST_NORMAL} unseen NORMAL scenarios...")
    normal_test = pd.DataFrame(
        [observation() for _ in range(TEST_NORMAL)], columns=FEATURES
    )
    print(f"Testing on {TEST_LEAK} simulated LEAK scenarios at junction {LEAK_TEST_JUNCTION}...")
    leak_test = pd.DataFrame(
        [observation(leak_junction=LEAK_TEST_JUNCTION) for _ in range(TEST_LEAK)],
        columns=FEATURES,
    )

    normal_predictions = model.predict(normal_test)
    leak_predictions = model.predict(leak_test)
    fp_rate = np.mean(normal_predictions == -1)  # false alarms
    detection_rate = np.mean(leak_predictions == -1)  # caught simulated leaks

    print("\n--- Unsupervised anomaly detection results ---")
    print("Sensors:", ", ".join(FEATURES))
    print(f"False-alarm rate (unseen normal runs): {fp_rate:.1%}")
    print(f"Detection rate (simulated J{LEAK_TEST_JUNCTION} leaks): {detection_rate:.1%}")

    demo = observation(leak_junction=LEAK_TEST_JUNCTION)
    predicted, score = classify(model, demo)
    print("\n--- Single hidden-leak demonstration ---")
    print("Measurements:", dict(zip(FEATURES, [round(v, 3) for v in demo])))
    print("Prediction:", predicted)
    print(f"Anomaly score: {score:.4f} (negative = anomalous)")
    print("Note: the model was not given the actual leak location.")

    evaluated = pd.concat([
        normal_test.assign(actual_scenario="normal", predicted_anomaly=normal_predictions == -1),
        leak_test.assign(actual_scenario=f"leak_at_{LEAK_TEST_JUNCTION}", predicted_anomaly=leak_predictions == -1),
    ], ignore_index=True)
    evaluated.to_csv(OUTPUT_DIR / "evaluation_results.csv", index=False)
    print(f"\nSaved model and CSV files in: {OUTPUT_DIR.resolve()}")
    print("This stage detects unusual readings; it does NOT localize the leak yet.")


if __name__ == "__main__":
    main()
